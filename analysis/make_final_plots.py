"""Generate the custom final ablation plots.

Important:
`traces/trace.jsonl` stores only `doc_id` and final `fused` score for hits.
It does NOT contain candidate text or raw BM25 values, so
`plots/length_vs_bm25.png` cannot be reconstructed from the JSONL file.

That plot is generated by the official:
    python rubbish.py bekesh

This script therefore preserves any existing official
`plots/length_vs_bm25.png` and generates only the custom ablation figures.

Usage:
    python -m analysis.make_final_plots
"""

from pathlib import Path
import matplotlib.pyplot as plt


ROOT = Path(__file__).resolve().parents[1]
PLOT_DIR = ROOT / "plots"


def hybrid_ablation() -> None:
    methods = ["Count", "TF-IDF", "BM25"]
    h1 = [20, 50, 60]
    h3 = [45, 60, 70]
    h5 = [70, 75, 75]

    x = list(range(len(methods)))
    w = 0.24

    plt.figure(figsize=(8, 5))
    plt.bar([v - w for v in x], h1, width=w, label="Hit@1")
    plt.bar(x, h3, width=w, label="Hit@3")
    plt.bar([v + w for v in x], h5, width=w, label="Hit@5")
    plt.xticks(x, methods)
    plt.ylim(0, 100)
    plt.ylabel("Recall (%)")
    plt.title("Hybrid Retrieval Ablation — Non-Exact Paraphrase DEV")
    plt.legend()
    plt.tight_layout()
    plt.savefig(PLOT_DIR / "hybrid_ablation.png", dpi=180)
    plt.close()


def rerank_ablation() -> None:
    metrics = ["H@1", "H@3", "H@5", "H@20"]
    before = [55, 70, 75, 90]
    after = [60, 70, 75, 90]

    x = list(range(len(metrics)))
    w = 0.34

    plt.figure(figsize=(8, 5))
    plt.bar([v - w / 2 for v in x], before, width=w, label="Before rerank")
    plt.bar([v + w / 2 for v in x], after, width=w, label="After rerank")
    plt.xticks(x, metrics)
    plt.ylim(0, 100)
    plt.ylabel("Recall (%)")
    plt.title("Hybrid Candidate Pool — Reranker Ablation")
    plt.legend()
    plt.tight_layout()
    plt.savefig(PLOT_DIR / "hybrid_rerank_ablation.png", dpi=180)
    plt.close()


def chunking_ablation() -> None:
    metrics = [
        "Bad internal\nboundary",
        "Intact\nsentence",
        "Numeric phrase\npreserved",
        "Metadata\ncoverage",
    ]
    fixed = [98.2, 82.2, 99.4, 0.0]
    final = [1.5, 94.7, 100.0, 100.0]

    x = list(range(len(metrics)))
    w = 0.34

    plt.figure(figsize=(9, 5.4))
    plt.bar([v - w / 2 for v in x], fixed, width=w, label="Fixed 300-char")
    plt.bar([v + w / 2 for v in x], final, width=w, label="Boundary-aware")
    plt.xticks(x, metrics)
    plt.ylim(0, 110)
    plt.ylabel("Rate (%)")
    plt.title("Chunking Quality Ablation")
    plt.legend()
    plt.tight_layout()
    plt.savefig(PLOT_DIR / "chunking_ablation.png", dpi=180)
    plt.close()


def judge_ablation() -> None:
    metrics = ["Routing\naccuracy", "Clarification\nF1", "Context\nsavings"]
    initial = [93.3, 40.0, 30.7]
    final = [100.0, 100.0, 37.3]

    x = list(range(len(metrics)))
    w = 0.34

    plt.figure(figsize=(8, 5.2))
    plt.bar([v - w / 2 for v in x], initial, width=w, label="Initial Judge")
    plt.bar([v + w / 2 for v in x], final, width=w, label="Final Judge")
    plt.xticks(x, metrics)
    plt.ylim(0, 110)
    plt.ylabel("Percent (%)")
    plt.title("Adaptive System-1 Judge — Before vs Final")
    plt.legend()
    plt.tight_layout()
    plt.savefig(PLOT_DIR / "judge_ablation.png", dpi=180)
    plt.close()


def main() -> None:
    PLOT_DIR.mkdir(parents=True, exist_ok=True)

    hybrid_ablation()
    rerank_ablation()
    chunking_ablation()
    judge_ablation()

    official_plot = PLOT_DIR / "length_vs_bm25.png"

    print("Generated custom plots:")
    print("- plots/hybrid_ablation.png")
    print("- plots/hybrid_rerank_ablation.png")
    print("- plots/chunking_ablation.png")
    print("- plots/judge_ablation.png")

    if official_plot.exists():
        print("- plots/length_vs_bm25.png already exists; preserved unchanged.")
    else:
        print(
            "WARNING: plots/length_vs_bm25.png is missing. "
            "It cannot be reconstructed from trace.jsonl because the trace "
            "records do not contain raw BM25 scores or candidate text. "
            "The official `python rubbish.py bekesh` generates it."
        )


if __name__ == "__main__":
    main()
